/**
 * 意图词库 —— 离线引擎的知识层。
 *
 * 设计说明（也是产品说明的一部分，不做夸大）：
 * 这里保存的是「人工写好的意图 → 六种语气的改写素材」。
 * 引擎在本地做三件事：关键词/句式命中意图、抽取实体、按风格配方重排句子。
 * 它不等于大模型的理解能力：命中不了意图时会明确降级为「泛化改写」，
 * 并在结果上标注 lowerConfidence，不会假装看懂了。
 *
 * 每个意图必须为六种风格都提供素材，否则自测会报错（selftest 会全量校验）。
 */
export type IntentId =
  | 'postpone'
  | 'vaguePromise'
  | 'declineSoft'
  | 'refuseDirect'
  | 'complaint'
  | 'waiting'
  | 'askOpinion'
  | 'priceHaggle'
  | 'bluffWarn'
  | 'passiveJab'
  | 'jargon'
  | 'serviceRule'
  | 'thanks'
  | 'apology'
  | 'askLeave'
  | 'remindPromise'
  | 'blameForget'
  | 'paintPie'
  | 'generic';

export interface Intent {
  id: IntentId;
  /** 人话标签：这一版结果在说什么 */
  label: string;
  /** 强匹配：命中即判定 */
  patterns: RegExp[];
  /** 弱匹配关键词，用于打分排序 */
  keywords: string[];
  truth: string[];
  eq: string[];
  sharp: string[];
  office: string[];
  sarcasm: string[];
  meme: string[];
  /** 利害关系句，用来给大白话/犀利版补一刀 */
  stake: string[];
  /** X 短文案素材 */
  x: string[];
  /**
   * 同分时的优先级；客套类（谢谢/抱歉）设为负数，
   * 因为「不好意思，这个我做不了」的实质是拒绝，不是道歉。
   */
  priority?: number;
}

